// npm run db:pull — regenerate src/schema.ts and src/relations.ts from the database in DATABASE_URL.
// Run it after applying a new migration, then commit the two files.
import { execSync } from 'node:child_process';
import fs from 'node:fs';

if (!process.env.DATABASE_URL) { console.error('Set DATABASE_URL first.'); process.exit(1); }
fs.rmSync('.pull', { recursive: true, force: true });
execSync('npx drizzle-kit pull', { stdio: 'inherit' });

const header = '// Generated by `npm run db:pull` from the live schema. Do not edit by hand.\n';
// Supabase's auth.users comes from drizzle-orm/supabase instead of being introspected.
let schema = fs.readFileSync('.pull/schema.ts', 'utf8');
if (/\busers\.id\b/.test(schema)) schema = schema.replace(/^(import .*\n)/, `$1import { authUsers as users } from "drizzle-orm/supabase"\n`);
let relations = fs.readFileSync('.pull/relations.ts', 'utf8')
  .replace(/,\s*usersInAuth(?=[,\s}])/, '')
  .replace(/^(import \{ relations \}.*\n)/m, `$1import { authUsers as usersInAuth } from "drizzle-orm/supabase";\n`)
  .replace(/export const usersInAuthRelations = relations\(usersInAuth, \(\{many\}\) => \(\{[\s\S]*?\n\}\)\);\n?/, '');

fs.writeFileSync('src/schema.ts', header + schema);
fs.writeFileSync('src/relations.ts', header + relations);
fs.rmSync('.pull', { recursive: true, force: true });
console.log('Updated src/schema.ts and src/relations.ts');
